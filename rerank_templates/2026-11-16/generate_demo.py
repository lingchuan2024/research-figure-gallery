"""Generate clearly synthetic paired observations; never reads experiment logs."""
from pathlib import Path
import csv
import hashlib
import json
import numpy as np

HERE = Path(__file__).resolve().parent
FIELDS = ['benchmark', 'question_id', 'subset', 'method', 'score', 'status',
          'wall_seconds', 'rerank_seconds', 'main_input_tokens',
          'reranker_input_tokens', 'rerank_events', 'scored_passages']


def main():
    rng = np.random.default_rng(20261116)
    rows = []
    methods = ['baseline', 'auto_rerank', 'v14']
    for i in range(120):
        subset = ['Bridge', 'Comparison', 'Direct'][i // 40]
        difficulty = rng.uniform()
        base_seconds = float(rng.lognormal(3.7, .62))
        base_tokens = int(rng.lognormal(9.1, .6))
        success_offsets = {'Bridge': [0, .09, .18], 'Comparison': [0, .08, .06], 'Direct': [0, -.04, -.02]}[subset]
        for j, method in enumerate(methods):
            events = 0 if j == 0 else (int(rng.integers(5, 13)) if j == 1 else int(rng.integers(0, 6)))
            scoring = 0.0 if not events else float(events * rng.uniform(.35, .8))
            elapsed = float(base_seconds * [1., 1.28, .92][j] * rng.lognormal(0, .08) + scoring)
            status = 'timeout' if elapsed >= 240 else ('no_final' if i % 47 == 0 else 'complete')
            score = int(difficulty < .57 + success_offsets[j] + float(rng.normal(0, .055))) if status == 'complete' else 0
            rows.append(dict(benchmark='DemoQA', question_id=f'q{i+1:03d}', subset=subset,
                method=method, score=score, status=status, wall_seconds=round(min(elapsed, 240), 6),
                rerank_seconds=round(scoring, 6), main_input_tokens=max(1, int(base_tokens * [1., .85, .73][j] * rng.lognormal(0, .05))),
                reranker_input_tokens=events * int(rng.integers(300, 900)), rerank_events=events,
                scored_passages=events * int(rng.integers(30, 90))))
    folder = HERE / 'data/demo'
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / 'observations.csv'
    with target.open('w', encoding='utf-8', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    with (HERE / 'data/observations_header.csv').open('w', encoding='utf-8', newline='') as stream:
        csv.writer(stream).writerow(FIELDS)
    (folder / 'provenance.json').write_text(json.dumps({
        'data_kind': 'synthetic', 'seed': 20261116, 'questions': 120, 'methods': methods,
        'rows': len(rows), 'generator': 'generate_demo.py',
        'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        'note': 'All values generated by illustrative random rules. No model, retriever, benchmark or real timing was executed. Method names label hypothetical conditions; differences are not research findings.'
    }, indent=2) + '\n')
    print(f'Generated {len(rows)} synthetic rows: {target}')


if __name__ == '__main__':
    main()
